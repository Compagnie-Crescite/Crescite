-- Crescite : signaler un retard ou un imprévu à l'équipe d'une date, depuis l'espace de l'équipe (le geste « Retard »
-- d'une date). À exécuter après les huit premiers scripts, de la même façon (SQL Editor → New query → coller → Run). Il
-- peut être relancé sans dommage et ne touche qu'à ce qui commence par crescite_.
--
-- Ce que le script ajoute :
--   crescite_signaler(d, texte_)   l'alerte part : une notification à chaque personne de l'équipe de la date qui a un
--                                  compte (crescite_membres_date : les présents de la date, et la distribution « en
--                                  tournée » qui n'en a pas été retirée), et à chaque administrateur qui a une fiche ;
--                                  jamais à son auteur. Elle arrive dans l'application (onglet Notifications, en temps
--                                  réel) et sur les téléphones abonnés, par le déclencheur des notifications du troisième
--                                  script. Seules l'équipe de la date et l'administration l'envoient, pour une date à
--                                  venir ; 280 caractères au plus ; cinq alertes par heure et par compte. Elle rend le
--                                  nombre de personnes prévenues.
--   crescite_signalements          chaque alerte envoyée : la date, son auteur, le texte, combien de personnes l'ont
--                                  reçue. L'auteur relit les siennes, l'administration toutes ; personne ne les écrit
--                                  à la main (seule la fonction le fait). L'espace de l'équipe y lit une ligne pour savoir
--                                  si ce script est passé : avant lui, le geste « Retard » ne se montre pas.

begin;

create table if not exists public.crescite_signalements (
  id bigint generated by default as identity primary key,
  date_id bigint not null references public.crescite_dates (id) on delete cascade,
  personne_id bigint references public.crescite_personnes (id) on delete set null,   -- l'auteur (vide : un administrateur sans fiche)
  user_id uuid references auth.users (id) on delete set null,                         -- son compte : la limite se compte par compte
  texte text not null,
  prevenus integer not null default 0,                                                -- combien de personnes l'ont reçue
  cree_le timestamptz not null default now()
);
create index if not exists crescite_signalements_compte on public.crescite_signalements (user_id, cree_le desc);
create index if not exists crescite_signalements_date on public.crescite_signalements (date_id);

-- l'alerte : la notification de chacun s'écrit ici, pas par crescite_notifier, qui fondrait deux alertes du même quart
-- d'heure en une seule (une mise à jour, qui ne part pas vers les téléphones). Elle porte le lien de la date mais pas son
-- date_id : un message de l'administration envoyé dans le quart d'heure (crescite_prevenir_equipe) ne vient pas la
-- réécrire, et sur le téléphone elle ne remplace pas une autre notification de la date encore en attente.
create or replace function public.crescite_signaler(d bigint, texte_ text) returns integer
language plpgsql security definer set search_path = public as $$
declare
  moi bigint := public.crescite_moi();
  t text := btrim(regexp_replace(coalesce(texte_, ''), '\s+', ' ', 'g'));
  sp bigint;
  qui text;
  dest bigint[];
begin
  if auth.uid() is null or not (public.crescite_est_admin() or public.crescite_membre_date(d)) then
    raise exception 'Réservé à l''équipe de cette date et à l''administration' using errcode = '42501';
  end if;
  select spectacle_id into sp from public.crescite_dates where id = d;
  if sp is null then raise exception 'Date % introuvable', d using errcode = '22023'; end if;
  if not public.crescite_a_venir(d) then raise exception 'Cette date est passée' using errcode = '22023'; end if;
  if t = '' then raise exception 'Le message est vide' using errcode = '22023'; end if;
  if char_length(t) > 280 then raise exception 'Le message dépasse 280 caractères' using errcode = '22023'; end if;
  -- un compte à la fois : deux alertes envoyées au même instant ne passent pas ensemble sous la limite
  perform pg_advisory_xact_lock(hashtext('crescite_signaler ' || auth.uid()::text));
  if (select count(*) from public.crescite_signalements
      where user_id = auth.uid() and cree_le > now() - interval '1 hour') >= 5 then
    -- PT429 : PostgREST répond 429 (trop de demandes)
    raise exception 'Cinq alertes en une heure : c''est le maximum. Appelez l''équipe.' using errcode = 'PT429';
  end if;
  select nullif(concat_ws(' ', pe.prenom, pe.nom), '') into qui from public.crescite_personnes pe where pe.id = moi;
  dest := array(
    select distinct x.p from (
      select public.crescite_membres_date(d) as p
      union
      select v.personne_id from public.crescite_admins a join public.crescite_personnes_privees v on v.user_id = a.user_id
    ) x
    where x.p is distinct from moi);
  insert into public.crescite_notifications (personne_id, type, titre, texte, date_id, spectacle_id, lien)
  select p, 'message', 'Retard ou imprévu : ' || coalesce(qui, 'l’administration'),
         concat_ws(' · ', t, public.crescite_date_texte(d)), null, sp, '#/date/' || d
  from unnest(dest) p;
  insert into public.crescite_signalements (date_id, personne_id, user_id, texte, prevenus)
  values (d, moi, auth.uid(), t, cardinality(dest));
  return cardinality(dest);
end;
$$;

-- ------------------------------------------------------------------------------------------------ règles d'accès

alter table public.crescite_signalements enable row level security;

-- les règles de ce script s'appellent signal_… : on les refait à chaque passage, sans toucher aux autres
do $$
declare p record;
begin
  for p in select policyname from pg_policies
           where schemaname = 'public' and tablename = 'crescite_signalements' and policyname like 'signal\_%' loop
    execute format('drop policy %I on public.crescite_signalements', p.policyname);
  end loop;
end $$;

-- chacun relit ses alertes, l'administration toutes ; aucune règle d'écriture : seule crescite_signaler écrit
create policy signal_lecture on public.crescite_signalements for select to authenticated
  using (user_id = (select auth.uid()) or (select public.crescite_est_admin()));

revoke all on public.crescite_signalements from anon, authenticated, public;
grant select on public.crescite_signalements to authenticated;
grant all on public.crescite_signalements to service_role;
grant execute on function public.crescite_signaler(bigint, text) to authenticated;
revoke execute on function public.crescite_signaler(bigint, text) from anon, public;

commit;

notify pgrst, 'reload schema';

-- ce qui est en place
select 'alertes de retard' as "élément",
  case when exists (select 1 from pg_proc where proname = 'crescite_signaler')
        and (select count(*) from pg_policies where schemaname = 'public' and tablename = 'crescite_signalements'
                                                and policyname like 'signal\_%') = 1
    then 'prêtes : l''équipe d''une date prévient les autres et l''administration (cinq alertes par heure et par compte)'
    else 'incomplètes : relancez ce script' end as "état"
union all
select 'administrateurs prévenus', case (select count(*) from public.crescite_admins a
                                        join public.crescite_personnes_privees v on v.user_id = a.user_id)
  when 0 then 'aucun : un administrateur n''est prévenu que si son compte est relié à une fiche de l''équipe'
  when 1 then 'un (son compte est relié à une fiche de l''équipe)'
  else (select count(*) from public.crescite_admins a join public.crescite_personnes_privees v on v.user_id = a.user_id)
       || ' (leurs comptes sont reliés à une fiche de l''équipe)' end;
