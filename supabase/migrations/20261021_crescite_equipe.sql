-- Avant d'ouvrir des comptes à l'équipe : les tables qui ne sont pas à la compagnie et qu'un compte connecté pourrait
-- lire ou modifier (sans règle d'accès, ou avec une règle qui ne regarde pas qui est connecté). Rien ne change ici :
