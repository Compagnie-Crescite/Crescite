-- Crescite : l'équipe. Une fiche par personne (comédiens, création, technique, administration), la distribution de
-- chaque spectacle, l'équipe de chaque date, les documents de l'équipe (le texte, le dossier…) et les feuilles de route.
-- Chaque personne de l'équipe a son espace (equipe/) : sa tournée, les horaires, les feuilles de route, les documents.
--
-- À exécuter après 20261020_crescite_base.sql, d'un seul bloc : SQL Editor → New query → coller ce fichier → Run.
-- Il peut être relancé sans dommage. Comme le premier, il ne touche à rien qui ne commence pas par crescite_.
-- Le dernier résultat affiché liste ce qu'il faut vérifier avant d'ouvrir des comptes à l'équipe : les comptes de ce
-- projet sont aussi ceux du site adrienvada.fr, et une table personnelle ouverte à « tout compte connecté » le serait
-- aussi pour eux.
--
-- Ce que le script ajoute :
--   crescite_personnes          la fiche publique : nom, métiers, photo et son crédit (montrés sur les pages de spectacle)
--   crescite_personnes_privees  le contact (adresse électronique, téléphone…) et le compte : lus par la personne et l'administration
--   crescite_personnes_suivi    les notes de l'administration sur une personne : jamais lues par elle
--   crescite_distributions      qui fait quoi dans chaque spectacle (jeu, mise en scène, lumières, régie…)
--   crescite_equipes            l'équipe d'une date, quand elle change de la distribution : remplacements, renforts, absences
--   crescite_documents          les documents de l'équipe : le texte, le dossier, la fiche technique (fichier ou lien)
--   crescite_feuilles           les feuilles de route, une par date : composées depuis la base, complétées, publiées
--   crescite_spectacles.feuille_modele   le déroulé type d'une journée de représentation, pour composer les feuilles
--   le dossier de stockage « crescite-equipe », privé : les fichiers des documents

begin;

-- ------------------------------------------------------------------------------------------------ les personnes

create table if not exists public.crescite_personnes (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),   -- « lauren-toulin »
  prenom text,
  nom text not null,
  metiers text[] not null default '{}',            -- « comédienne », « régisseur général », « administratrice »…
  bio text,                                        -- quelques lignes, si on veut les publier
  photo text,                                      -- chemin dans le stockage « crescite » (public) : equipe/<slug>.webp
  photo_credit text,                               -- montré sous la photo : « © Prénom Nom »
  photo_source text,                               -- d'où vient la photo (page web, dossier…) : pour l'administration
  photo_publique boolean not null default false,   -- la photo n'apparaît sur le site que si l'accord est donné
  publie boolean not null default true,            -- la fiche apparaît sur les pages de spectacle
  ordre integer not null default 100,
  cree_le timestamptz not null default now(),
  modifie_le timestamptz not null default now(),
  modifie_par uuid
);

-- le contact et le compte d'une personne : lus par elle-même et par l'administration, jamais par le site
create table if not exists public.crescite_personnes_privees (
  personne_id bigint primary key references public.crescite_personnes (id) on delete cascade,
  email text,                                      -- l'adresse du compte : la personne se connecte avec elle
  telephone text,
  ville text,                                      -- d'où elle part en tournée
  regime text,                                     -- ce que l'accueil doit savoir pour les repas
  urgence text,                                    -- qui prévenir en cas d'urgence
  user_id uuid unique references auth.users (id) on delete set null,   -- le compte, rattaché à la première connexion
  modifie_le timestamptz not null default now(),
  modifie_par uuid
);
create unique index if not exists crescite_personnes_privees_email on public.crescite_personnes_privees (lower(email));

-- les notes de l'administration sur une personne (contrats, disponibilités…) : jamais lues par elle
create table if not exists public.crescite_personnes_suivi (
  personne_id bigint primary key references public.crescite_personnes (id) on delete cascade,
  notes text,
  modifie_le timestamptz not null default now(),
  modifie_par uuid
);

-- ------------------------------------------------------------------------------------------------ distributions et équipes

-- qui fait quoi dans un spectacle, dans l'ordre de sa fiche
create table if not exists public.crescite_distributions (
  id bigint generated by default as identity primary key,
  spectacle_id bigint not null references public.crescite_spectacles (id) on delete cascade,
  personne_id bigint not null references public.crescite_personnes (id) on delete cascade,
  categorie text not null default 'jeu' check (categorie in ('jeu', 'creation', 'technique', 'production')),
  fonction text not null default '',               -- « Mise en scène et adaptation », « Régisseur général »… ; vide pour le jeu
  role text,                                       -- le personnage, si on veut le dire
  alternance text,                                 -- « en alternance avec … » : montré tel quel
  en_tournee boolean not null default true,        -- part en tournée par défaut (la création lumière, souvent, non)
  publie boolean not null default true,            -- apparaît sur la page du spectacle
  ordre integer not null default 100,
  modifie_le timestamptz not null default now(),
  modifie_par uuid,
  unique (spectacle_id, personne_id, categorie, fonction)
);
create index if not exists crescite_distributions_personne on public.crescite_distributions (personne_id);

-- l'équipe d'une date : par défaut, la distribution « en tournée » du spectacle ; ici, ce qui change pour cette date
create table if not exists public.crescite_equipes (
  date_id bigint not null references public.crescite_dates (id) on delete cascade,
  personne_id bigint not null references public.crescite_personnes (id) on delete cascade,
  present boolean not null default true,           -- faux : la personne ne part pas sur cette date (remplacée)
  fonction text,                                   -- ce qu'elle fait sur cette date (« remplace Lauren Toulin »…)
  note text,
  modifie_le timestamptz not null default now(),
  modifie_par uuid,
  primary key (date_id, personne_id)
);
create index if not exists crescite_equipes_personne on public.crescite_equipes (personne_id);

-- ------------------------------------------------------------------------------------------------ documents et feuilles de route

create table if not exists public.crescite_documents (
  id bigint generated by default as identity primary key,
  spectacle_id bigint references public.crescite_spectacles (id) on delete cascade,   -- vide : pour toute la compagnie
  type text not null default 'autre' check (type in ('texte', 'dossier', 'fiche_technique', 'plan', 'autre')),
  titre text not null,
  fichier text,                                    -- chemin dans le stockage privé « crescite-equipe »
  url text,                                        -- ou un lien (le texte sur Wikisource, un dossier en ligne…)
  pour text not null default 'equipe' check (pour in ('equipe', 'administration')),
  ordre integer not null default 100,
  cree_le timestamptz not null default now(),
  modifie_le timestamptz not null default now(),
  modifie_par uuid,
  check (fichier is not null or url is not null)
);
create index if not exists crescite_documents_spectacle on public.crescite_documents (spectacle_id, ordre);

-- une feuille de route par date. contenu (composé depuis la base, puis complété par l'administration) :
--   {lieu: {nom, adresse, commune, acces, parking, loges, details}, trajet: {depart, distance_km, duree_min, details},
--    planning: [{jour, heure, fin, quoi, qui, ou}], transport: [{jour, heure, mode, trajet, qui, details}],
--    hebergement: [{nom, adresse, telephone, arrivee, depart, details}], repas: [{jour, heure, ou, details}],
--    equipe: [{personne_id, nom, fonction, telephone}], contacts: [{nom, role, telephone, email}],
--    documents: [document_id], notes,
--    et, posés par la composition (admin/feuille.js) : representations (l'instantané des horaires composés), lieu.itineraire,
--    trajet.estime, planning[].rep (la représentation d'une ligne), _base (la composition précédente, pour recomposer
--    sans perdre ce qui a été saisi)}
create table if not exists public.crescite_feuilles (
  id bigint generated by default as identity primary key,
  date_id bigint not null unique references public.crescite_dates (id) on delete cascade,
  titre text,
  contenu jsonb not null default '{}',
  statut text not null default 'brouillon' check (statut in ('brouillon', 'publiee')),
  publiee_le timestamptz,
  version integer not null default 1,
  cree_le timestamptz not null default now(),
  modifie_le timestamptz not null default now(),
  modifie_par uuid
);

-- le déroulé type d'une journée de représentation : [{avant_min, quoi, qui, fin?, jours?}] (avant_min : minutes avant le
-- lever de rideau ; négatif : après la fin ; fin: true pour « à la fin » ; jours : 'premier', 'tous' ou 'dernier' quand
-- la date dure plusieurs jours). La feuille de route le pose avant la première représentation du jour et après la dernière
alter table public.crescite_spectacles add column if not exists feuille_modele jsonb not null default '[]';

-- ------------------------------------------------------------------------------------------------ qui est qui

-- la fiche de la personne connectée (ou rien)
create or replace function public.crescite_moi() returns bigint
language sql stable security definer set search_path = public as $$
  select personne_id from public.crescite_personnes_privees where user_id = auth.uid()
$$;

-- vrai si la personne connectée part sur cette date : dans l'équipe de la date, ou dans la distribution « en tournée »
-- du spectacle sans avoir été retirée de la date
create or replace function public.crescite_membre_date(d bigint) returns boolean
language sql stable security definer set search_path = public as $$
  with moi as (select public.crescite_moi() as id)
  select exists (select 1 from moi where moi.id is not null and (
           exists (select 1 from public.crescite_equipes e where e.date_id = d and e.personne_id = moi.id and e.present)
        or exists (select 1 from public.crescite_dates x join public.crescite_distributions di on di.spectacle_id = x.spectacle_id
                   where x.id = d and di.personne_id = moi.id and di.en_tournee
                     and not exists (select 1 from public.crescite_equipes e
                                     where e.date_id = d and e.personne_id = moi.id and not e.present))))
$$;

-- vrai si la personne connectée travaille sur ce spectacle : dans sa distribution, ou dans l'équipe d'une de ses dates
create or replace function public.crescite_membre_spectacle(s bigint) returns boolean
language sql stable security definer set search_path = public as $$
  with moi as (select public.crescite_moi() as id)
  select exists (select 1 from moi where moi.id is not null and (
           exists (select 1 from public.crescite_distributions di where di.spectacle_id = s and di.personne_id = moi.id)
        or exists (select 1 from public.crescite_equipes e join public.crescite_dates x on x.id = e.date_id
                   where x.spectacle_id = s and e.personne_id = moi.id and e.present)))
$$;

-- à la première connexion : rattache le compte à la fiche dont l'adresse est celle du compte (si aucune fiche ne l'est
-- encore) ; renvoie l'identifiant de la fiche, ou rien
create or replace function public.crescite_rattacher() returns bigint
language plpgsql security definer set search_path = public as $$
declare
  courriel text := lower(nullif(auth.jwt() ->> 'email', ''));
  p bigint;
begin
  if auth.uid() is null then return null; end if;
  select personne_id into p from public.crescite_personnes_privees where user_id = auth.uid();
  if p is not null or courriel is null then return p; end if;
  update public.crescite_personnes_privees set user_id = auth.uid(), modifie_le = now()
   where lower(email) = courriel and user_id is null
  returning personne_id into p;
  return p;
end;
$$;

-- la tournée de la personne connectée : ses dates (passées comprises), avec le spectacle, le lieu, les représentations,
-- l'équipe et la feuille de route si elle est publiée. saison : « 2026-2027 », ou vide pour tout
create or replace function public.crescite_ma_tournee(saison_voulue text default null) returns jsonb
language sql stable security invoker set search_path = public as $$
  select coalesce(jsonb_agg(x order by x ->> 'debut', (x ->> 'id')::bigint), '[]'::jsonb) from (
    select jsonb_build_object(
      'id', d.id, 'debut', d.debut, 'fin', d.fin, 'precision', d.precision, 'saison', d.saison, 'public', d.public,
      'statut', d.statut, 'intitule', d.intitule, 'details', d.details, 'lien', d.lien, 'nature', d.nature,
      'spectacle', jsonb_build_object('id', s.id, 'slug', s.slug, 'titre', s.titre, 'duree', s.duree, 'univers', s.univers),
      'lieu', case when l.id is null then null else jsonb_build_object('id', l.id, 'nom', l.nom, 'commune', l.commune,
              'departement', l.departement, 'adresse', l.adresse, 'latitude', l.latitude, 'longitude', l.longitude,
              'site_web', l.site_web) end,
      'representations', coalesce((select jsonb_agg(jsonb_build_object('id', r.id, 'jour', r.jour, 'heure', r.heure, 'fin', r.fin,
              'public', r.public, 'annulee', r.annulee, 'note', r.note) order by r.jour, r.heure nulls last)
              from public.crescite_representations r where r.date_id = d.id), '[]'::jsonb),
      'feuille', (select jsonb_build_object('id', f.id, 'version', f.version, 'publiee_le', f.publiee_le)
                  from public.crescite_feuilles f where f.date_id = d.id and f.statut = 'publiee')
    ) as x
    from public.crescite_dates d
    join public.crescite_spectacles s on s.id = d.spectacle_id
    left join public.crescite_lieux l on l.id = d.lieu_id
    where public.crescite_membre_date(d.id) and (saison_voulue is null or d.saison = saison_voulue)
  ) t
$$;

-- une personne ne change sur sa fiche privée ni son adresse de compte ni son rattachement : l'administration, si
create or replace function public.crescite_personnes_privees_garde() returns trigger
language plpgsql as $$
begin
  -- service_role (les imports) et le propriétaire des fonctions (crescite_rattacher) passent
  if current_user not in ('service_role', 'postgres', 'supabase_admin') and not public.crescite_est_admin()
     and (new.email is distinct from old.email or new.user_id is distinct from old.user_id
          or new.personne_id is distinct from old.personne_id) then
    raise exception 'Seule l''administration change l''adresse du compte' using errcode = '42501';
  end if;
  return new;
end;
$$;

-- publier une feuille la date ; la republier (ou la modifier une fois publiée) augmente sa version
create or replace function public.crescite_feuilles_avant() returns trigger
language plpgsql as $$
begin
  if new.statut = 'publiee' and (tg_op = 'INSERT' or old.statut is distinct from 'publiee'
                                 or old.contenu is distinct from new.contenu or old.titre is distinct from new.titre) then
    if tg_op = 'UPDATE' and old.publiee_le is not null then new.version := old.version + 1; end if;
    new.publiee_le := now();
  end if;
  return new;
end;
$$;

