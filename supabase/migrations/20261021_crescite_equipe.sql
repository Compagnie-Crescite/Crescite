with souci as (
  select c.relname::text as "table", 'pas de règle d''accès (RLS désactivée)' as "à vérifier"
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity and c.relname not like 'crescite\_%'
  union all
  select p.tablename::text, format('règle « %s » (%s, pour %s) : %s', p.policyname, p.cmd, array_to_string(p.roles, ', '),
                                  coalesce(p.qual, p.with_check, 'toujours'))
  from pg_policies p
  where p.schemaname = 'public' and p.tablename not like 'crescite\_%'
    and p.roles && array['authenticated', 'public']::name[]
    -- une règle qui ne regarde pas qui est connecté, ou seulement s'il l'est (« auth.role() = 'authenticated' »,
    -- « auth.uid() is not null ») : tout compte de l'équipe y aurait droit
    and (coalesce(p.qual, '') || coalesce(p.with_check, '') !~ '(auth\.uid|auth\.jwt|auth\.email)'
         or coalesce(p.qual, '') || coalesce(p.with_check, '') ~* '(auth\.role\(\)\s*=\s*''authenticated''|auth\.uid\(\)\s*is\s+not\s+null)')
)
select * from souci
union all
select '—', 'rien à signaler : aucune table personnelle n''est ouverte à tout compte connecté'
where not exists (select 1 from souci);
