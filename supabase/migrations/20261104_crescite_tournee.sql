-- ------------------------------------------------------------------------------------------------ l'équipe du jour
-- les coordonnées de l'équipe d'une date, pour ses membres (et l'administration) : de quoi s'appeler et s'écrire en tournée
create or replace function public.crescite_equipe_du_jour(d bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select case when public.crescite_membre_date(d) or public.crescite_est_admin() then
    coalesce((select jsonb_agg(jsonb_build_object('personne_id', p.id, 'prenom', p.prenom, 'nom', p.nom, 'metiers', p.metiers,
                                                   'telephone', v.telephone, 'email', v.email, 'ville', v.ville) order by p.nom, p.prenom)
              from public.crescite_equipe_de_date(d) t join public.crescite_personnes p on p.id = t
              left join public.crescite_personnes_privees v on v.personne_id = p.id), '[]'::jsonb)
    else '[]'::jsonb end
$$;
grant execute on function public.crescite_equipe_du_jour(bigint) to authenticated;
grant execute on function public.crescite_equipe_de_date(bigint) to authenticated;

