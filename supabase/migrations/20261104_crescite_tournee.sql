-- monter dans un trajet (s'il reste une place), ou en descendre
create or replace function public.crescite_trajet_monter(t bigint, oui boolean) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  moi bigint := public.crescite_moi();
  x public.crescite_trajets;
begin
  if moi is null then raise exception 'Pas de fiche pour ce compte' using errcode = '42501'; end if;
  select * into x from public.crescite_trajets where id = t;
  if x.id is null then raise exception 'Trajet introuvable'; end if;
  if not public.crescite_membre_date(x.date_id) then raise exception 'Pas sur cette date' using errcode = '42501'; end if;
  if x.personne_id = moi then raise exception 'C’est votre trajet'; end if;
  if oui then
    if moi = any (x.passagers) then return jsonb_build_object('passagers', x.passagers);
    end if;
    if coalesce(array_length(x.passagers, 1), 0) >= x.places then raise exception 'Plus de place dans ce trajet'; end if;
    update public.crescite_trajets set passagers = array_append(passagers, moi), modifie_le = now() where id = t returning * into x;
  else
    update public.crescite_trajets set passagers = array_remove(passagers, moi), modifie_le = now() where id = t returning * into x;
  end if;
  return jsonb_build_object('passagers', x.passagers);
end;
$$;
grant execute on function public.crescite_trajet_monter(bigint, boolean) to authenticated;

