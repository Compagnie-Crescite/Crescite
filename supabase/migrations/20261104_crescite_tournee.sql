-- Crescite : la tournée vue par l'équipe (le seizième script). À exécuter après les précédents, de la même façon
-- (SQL Editor → New query → coller → Run). Il peut être relancé sans dommage et ne touche qu'à ce qui commence par
-- crescite_ (plus les règles du stockage privé « crescite-equipe », pour les photos du fil).
--
-- Ce que le script ajoute (lu et écrit par equipe/tournee.js ; l'administration lit les présences et les créneaux) :
--   crescite_presences      « Je serai là » / « Je ne pourrai pas » sur une date, et « J'ai lu » sur sa feuille de route
--                           (la version lue), par personne ; l'équipe de la date voit qui a confirmé
--   crescite_fil            le fil de discussion d'une date : messages, mentions (@Prénom Nom), photos (stockage privé,
--                           sous fil/<date>/) ; l'équipe de la date est prévenue de chaque message (notification « message »)
--   crescite_trajets        les trajets de chacun pour une date (aller, retour : train, voiture, camion…), les places, les
--                           passagers ; crescite_trajet_monter(t, oui) pour monter dans un trajet ou en descendre
--   crescite_checklists     la check-list personnelle d'une date, et le modèle de chacun (date_id vide)
--   crescite_creneaux       les créneaux libres qu'une personne propose à l'administration
--   crescite_equipe_du_jour les coordonnées (téléphone, adresse électronique) de l'équipe d'une date, pour ses membres

begin;

-- ------------------------------------------------------------------------------------------------ l'équipe d'une date
-- les personnes qui partent sur une date (la distribution en tournée, corrigée par l'équipe de la date), sans compte ou avec
create or replace function public.crescite_equipe_de_date(d bigint) returns setof bigint
language sql stable security definer set search_path = public as $$
  select distinct t.p from (
    select di.personne_id as p from public.crescite_dates x join public.crescite_distributions di on di.spectacle_id = x.spectacle_id
     where x.id = d and di.en_tournee
       and not exists (select 1 from public.crescite_equipes e where e.date_id = d and e.personne_id = di.personne_id and not e.present)
    union
    select e.personne_id from public.crescite_equipes e where e.date_id = d and e.present
  ) t
$$;

-- ------------------------------------------------------------------------------------------------ les présences
create table if not exists public.crescite_presences (
  date_id bigint not null references public.crescite_dates (id) on delete cascade,
  personne_id bigint not null references public.crescite_personnes (id) on delete cascade,
  statut text check (statut in ('present', 'absent', 'incertain')),
  motif text,
  feuille_lue_version integer,
  feuille_lue_le timestamptz,
  maj_le timestamptz not null default now(),
  primary key (date_id, personne_id)
);
alter table public.crescite_presences enable row level security;
drop policy if exists presences_lecture on public.crescite_presences;
drop policy if exists presences_ecriture on public.crescite_presences;
drop policy if exists presences_modification on public.crescite_presences;
drop policy if exists presences_suppression on public.crescite_presences;
create policy presences_lecture on public.crescite_presences for select to authenticated
  using (public.crescite_membre_date(date_id) or (select public.crescite_est_admin()));
create policy presences_ecriture on public.crescite_presences for insert to authenticated
  with check (personne_id = (select public.crescite_moi()) and public.crescite_membre_date(date_id));
create policy presences_modification on public.crescite_presences for update to authenticated
  using (personne_id = (select public.crescite_moi())) with check (personne_id = (select public.crescite_moi()));
create policy presences_suppression on public.crescite_presences for delete to authenticated
  using (personne_id = (select public.crescite_moi()) or (select public.crescite_est_admin()));
grant select, insert, update, delete on public.crescite_presences to authenticated;

create or replace function public.crescite_presences_maj() returns trigger
language plpgsql as $$ begin new.maj_le := now(); return new; end; $$;
drop trigger if exists crescite_presences_maj on public.crescite_presences;
create trigger crescite_presences_maj before update on public.crescite_presences for each row execute function public.crescite_presences_maj();

