-- chaque message prévient l'équipe de la date (jamais l'auteur), dans son espace et sur son téléphone s'il est abonné
create or replace function public.crescite_fil_prevenir() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  p bigint;
  sujet text;
  s bigint;
begin
  select coalesce(sp.titre, 'une date') || ' · ' || to_char(x.debut, 'DD/MM'), x.spectacle_id into sujet, s
    from public.crescite_dates x left join public.crescite_spectacles sp on sp.id = x.spectacle_id where x.id = new.date_id;
  for p in select * from public.crescite_equipe_de_date(new.date_id) loop
    if p is null or p = new.personne_id then continue; end if;
    if not exists (select 1 from public.crescite_personnes_privees v where v.personne_id = p and v.user_id is not null) then continue; end if;
    insert into public.crescite_notifications (personne_id, type, titre, texte, date_id, spectacle_id, lien)
    values (p, 'message', coalesce(new.auteur_nom, 'Quelqu’un') || ' · ' || coalesce(sujet, 'le fil'),
            case when new.texte <> '' then left(new.texte, 240) else coalesce('📎 ' || new.fichier_nom, 'Une photo') end,
            new.date_id, s, '#/date/' || new.date_id);
  end loop;
  return null;
end;
$$;
drop trigger if exists crescite_fil_prevenir on public.crescite_fil;
create trigger crescite_fil_prevenir after insert on public.crescite_fil for each row execute function public.crescite_fil_prevenir();

-- les photos du fil, dans le stockage privé de l'équipe, sous fil/<date>/ : l'équipe de la date les dépose et les lit
create or replace function public.crescite_fil_chemin(nom text) returns boolean
language sql stable security definer set search_path = public as $$
  select (storage.foldername(nom))[1] = 'fil' and (storage.foldername(nom))[2] ~ '^\d+$'
     and public.crescite_membre_date(((storage.foldername(nom))[2])::bigint)
$$;
drop policy if exists crescite_fil_lecture on storage.objects;
drop policy if exists crescite_fil_ajout on storage.objects;
drop policy if exists crescite_fil_suppression on storage.objects;
create policy crescite_fil_lecture on storage.objects for select to authenticated
  using (bucket_id = 'crescite-equipe' and public.crescite_fil_chemin(name));
create policy crescite_fil_ajout on storage.objects for insert to authenticated
  with check (bucket_id = 'crescite-equipe' and public.crescite_fil_chemin(name));
create policy crescite_fil_suppression on storage.objects for delete to authenticated
  using (bucket_id = 'crescite-equipe' and public.crescite_fil_chemin(name) and owner = auth.uid());

