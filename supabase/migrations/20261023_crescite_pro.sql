-- Crescite : l'espace des programmateurs et des directeurs de salle (pro/). La compagnie y ouvre, sur invitation, des
-- fichiers qui ne sont pas publics : les captations, des photos en haute définition, une fiche technique détaillée…
-- À exécuter après les trois premiers scripts, de la même façon (SQL Editor → New query → coller → Run). Il peut être
-- relancé sans dommage et ne touche qu'à ce qui commence par crescite_.
--
-- Ce que le script ajoute :
--   crescite_documents.pour          + 'salles' : un document réservé aux salles invitées (jamais au public, jamais à
--                                    l'équipe) ; un fichier du stockage privé « crescite-pro », ou un lien (une captation
--                                    sur Vimeo, YouTube en non répertorié, le Drive…)
--   crescite_acces_pro               une invitation : une structure (« Théâtre de … »), son contact, les spectacles qu'on lui
--                                    ouvre, une date de fin, et un jeton secret. Le lien envoyé : …/pro/#<jeton>
--   crescite_acces_pro_journal       qui a ouvert l'espace, et quel document, quand
--   « crescite-pro »                 le stockage privé de ces fichiers (50 Mo par fichier : une captation se partage en lien)
-- La page pro/ ne lit rien elle-même : la fonction « crescite-pro » (supabase/functions/crescite-pro) vérifie le jeton,
-- donne la liste des documents ouverts, et un lien de téléchargement d'une heure pour chaque fichier. Seule
-- l'administration lit et écrit ces tables.

begin;

-- ------------------------------------------------------------------------------------------------ les documents des salles

-- la liste complète (les documents communs aux programmateurs et aux établissements viennent du huitième script) :
-- relancé après lui, ce script ne refuse aucun document déjà rangé
alter table public.crescite_documents drop constraint if exists crescite_documents_pour_check;
alter table public.crescite_documents add constraint crescite_documents_pour_check
  check (pour in ('equipe', 'administration', 'pros', 'scolaires', 'salles', 'tous', 'pros_scolaires'));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('crescite-pro', 'crescite-pro', false, 52428800,
        array['application/pdf', 'image/jpeg', 'image/png', 'image/webp', 'video/mp4', 'application/zip'])
on conflict (id) do update set public = false, file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- ------------------------------------------------------------------------------------------------ les invitations

create table if not exists public.crescite_acces_pro (
  id bigint generated by default as identity primary key,
  nom text not null,                               -- la structure : « Théâtre de … », « Festival … »
  contact text,                                    -- la personne invitée
  courriel text,
  jeton text not null unique default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
  spectacles bigint[],                             -- les spectacles ouverts ; vide : tous ceux qui ont des documents
  expire_le date not null default (current_date + 90),
  actif boolean not null default true,
  notes text,                                      -- pour l'administration
  visites integer not null default 0,
  derniere_visite timestamptz,
  cree_le timestamptz not null default now(),
  cree_par uuid default auth.uid()
);
create index if not exists crescite_acces_pro_jeton on public.crescite_acces_pro (jeton);

create table if not exists public.crescite_acces_pro_journal (
  id bigint generated by default as identity primary key,
  acces_id bigint not null references public.crescite_acces_pro (id) on delete cascade,
  document_id bigint references public.crescite_documents (id) on delete set null,
  quoi text not null check (quoi in ('visite', 'ouverture')),
  quand timestamptz not null default now()
);
create index if not exists crescite_acces_pro_journal_acces on public.crescite_acces_pro_journal (acces_id, quand desc);

-- une invitation valide : active et pas encore échue
create or replace function public.crescite_pro_acces(j text) returns public.crescite_acces_pro
language sql stable security definer set search_path = public as $$
  select a.* from public.crescite_acces_pro a
  where a.jeton = j and a.actif and a.expire_le >= current_date and length(coalesce(j, '')) >= 32
$$;

-- les documents qu'une invitation ouvre : ceux des salles et ceux des pros (communs aux établissements compris : le
-- huitième script), pour ses spectacles
create or replace function public.crescite_pro_documents_de(a public.crescite_acces_pro) returns setof public.crescite_documents
language sql stable security definer set search_path = public as $$
  select d.* from public.crescite_documents d
  where d.pour in ('salles', 'pros', 'tous', 'pros_scolaires') and d.spectacle_id is not null
    and (case when coalesce(cardinality(a.spectacles), 0) = 0
              then exists (select 1 from public.crescite_documents x where x.spectacle_id = d.spectacle_id and x.pour = 'salles')
              else d.spectacle_id = any (a.spectacles) end)
$$;

-- ouvrir l'espace : l'invitation, ses spectacles et leurs documents (sans les chemins de fichiers) ; la visite est notée
create or replace function public.crescite_pro_ouvrir(j text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  a public.crescite_acces_pro;
  r jsonb;
begin
  a := public.crescite_pro_acces(j);
  if a.id is null then return null; end if;
  update public.crescite_acces_pro set visites = visites + 1, derniere_visite = now() where id = a.id;
  insert into public.crescite_acces_pro_journal (acces_id, quoi) values (a.id, 'visite');
  select jsonb_build_object(
    'acces', jsonb_build_object('nom', a.nom, 'contact', a.contact, 'expire_le', a.expire_le),
    'spectacles', coalesce(jsonb_agg(jsonb_build_object(
        'id', s.id, 'slug', s.slug, 'titre', s.titre, 'sous_titre', s.sous_titre, 'creation', s.creation,
        'photo', s.photo, 'univers', s.univers,
        'documents', (select jsonb_agg(jsonb_build_object('id', d.id, 'type', d.type, 'titre', d.titre, 'pour', d.pour,
                                                          'lien', d.url is not null) order by d.pour desc, d.ordre, d.id)
                      from public.crescite_pro_documents_de(a) d where d.spectacle_id = s.id))
      order by s.ordre, s.id), '[]'::jsonb))
  into r
  from public.crescite_spectacles s
  where exists (select 1 from public.crescite_pro_documents_de(a) d where d.spectacle_id = s.id);
  return r;
end;
$$;

-- ouvrir un document : son fichier (stockage et chemin) ou son lien, si l'invitation l'ouvre ; l'ouverture est notée
create or replace function public.crescite_pro_document(j text, doc bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  a public.crescite_acces_pro;
  d public.crescite_documents;
begin
  a := public.crescite_pro_acces(j);
  if a.id is null then return null; end if;
  select x.* into d from public.crescite_pro_documents_de(a) x where x.id = doc;
  if d.id is null then return null; end if;
  insert into public.crescite_acces_pro_journal (acces_id, document_id, quoi) values (a.id, d.id, 'ouverture');
  return jsonb_build_object('titre', d.titre, 'url', d.url, 'fichier', d.fichier,
                            'stockage', case when d.pour = 'salles' then 'crescite-pro' else 'crescite' end);
end;
$$;

-- ------------------------------------------------------------------------------------------------ règles d'accès

alter table public.crescite_acces_pro enable row level security;
alter table public.crescite_acces_pro_journal enable row level security;

-- les règles de ce script s'appellent pro_… : on les refait à chaque passage, sans toucher aux autres
do $$
declare p record;
begin
  for p in select policyname, tablename from pg_policies
           where schemaname = 'public' and tablename like 'crescite\_%' and policyname like 'pro\_%' loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
  for p in select policyname from pg_policies where schemaname = 'storage' and tablename = 'objects'
           and policyname like 'crescite\_pro\_%' loop
    execute format('drop policy %I on storage.objects', p.policyname);
  end loop;
end $$;

-- seule l'administration voit et gère les invitations et leur journal
create policy pro_admin on public.crescite_acces_pro for all to authenticated
  using ((select public.crescite_est_admin())) with check ((select public.crescite_est_admin()));
create policy pro_lecture on public.crescite_acces_pro_journal for select to authenticated
  using ((select public.crescite_est_admin()));
create policy pro_suppression on public.crescite_acces_pro_journal for delete to authenticated
  using ((select public.crescite_est_admin()));

-- le stockage « crescite-pro » : l'administration seule (la fonction crescite-pro signe les liens de téléchargement)
create policy crescite_pro_lecture on storage.objects for select to authenticated
  using (bucket_id = 'crescite-pro' and (select public.crescite_est_admin()));
create policy crescite_pro_ajout on storage.objects for insert to authenticated
  with check (bucket_id = 'crescite-pro' and (select public.crescite_est_admin()));
create policy crescite_pro_modification on storage.objects for update to authenticated
  using (bucket_id = 'crescite-pro' and (select public.crescite_est_admin()));
create policy crescite_pro_suppression on storage.objects for delete to authenticated
  using (bucket_id = 'crescite-pro' and (select public.crescite_est_admin()));

grant select, insert, update, delete on public.crescite_acces_pro to authenticated;
grant select, delete on public.crescite_acces_pro_journal to authenticated;
grant usage, select on sequence public.crescite_acces_pro_id_seq to authenticated;
grant all on public.crescite_acces_pro, public.crescite_acces_pro_journal to service_role;
revoke all on public.crescite_acces_pro, public.crescite_acces_pro_journal from anon;
revoke execute on function public.crescite_pro_acces(text), public.crescite_pro_documents_de(public.crescite_acces_pro),
  public.crescite_pro_ouvrir(text), public.crescite_pro_document(text, bigint) from anon, authenticated, public;

commit;

notify pgrst, 'reload schema';

-- ce qui est en place
select 'espace des salles' as "élément", 'prêt : invitations, journal et stockage « crescite-pro »' as "état"
union all
select 'stockage privé', case when exists (select 1 from storage.buckets where id = 'crescite-pro' and not public)
  then 'crescite-pro est privé' else 'crescite-pro manque' end;
