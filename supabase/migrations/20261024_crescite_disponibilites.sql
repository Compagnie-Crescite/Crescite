-- ------------------------------------------------------------------------------------------------ le planning

-- tout ce que le planning montre, de de à a (inclus) : réservé à l'équipe et à l'administration. Le motif d'une
-- indisponibilité ne part qu'à la personne elle-même et à l'administration ; une proposition, qu'à ses destinataires
-- et à l'administration.
create or replace function public.crescite_planning(de date, a date) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  moi bigint := public.crescite_moi();
  admin boolean := public.crescite_est_admin();
  t0 timestamptz := de::timestamptz;
  t1 timestamptz := (a + 1)::timestamptz;
begin
  if moi is null and not admin then raise exception 'Réservé à l''équipe' using errcode = '42501'; end if;
  return jsonb_build_object(
    'moi', moi, 'admin', admin,
    'personnes', (select coalesce(jsonb_agg(jsonb_build_object('id', pe.id, 'slug', pe.slug, 'prenom', pe.prenom, 'nom', pe.nom,
                    'metiers', pe.metiers, 'photo', case when pe.photo_publique then pe.photo end) order by pe.ordre, pe.nom), '[]'::jsonb)
                  from public.crescite_personnes pe
                  where exists (select 1 from public.crescite_distributions di where di.personne_id = pe.id)
                     or exists (select 1 from public.crescite_personnes_privees v where v.personne_id = pe.id and v.user_id is not null)),
    'indisponibilites', (select coalesce(jsonb_agg(jsonb_build_object('id', i.id, 'personne_id', i.personne_id, 'debut', i.debut,
                    'fin', i.fin, 'journee', i.journee, 'source', i.source,
                    'motif', case when admin or i.personne_id = moi then i.motif end) order by i.debut), '[]'::jsonb)
                  from public.crescite_indisponibilites i where i.debut < t1 and i.fin > t0),
    'dates', (select coalesce(jsonb_agg(jsonb_build_object('id', x.id, 'debut', x.debut, 'fin', x.fin, 'nature', x.nature,
                    'precision', x.precision, 'statut', x.statut, 'public', x.public,
                    'spectacle', jsonb_build_object('id', s.id, 'slug', s.slug, 'titre', s.titre,
                                                    'couleur', s.univers -> 'couleurs' ->> 'scene'),
                    'lieu', case when l.id is null then null else jsonb_build_object('nom', l.nom, 'commune', l.commune) end,
                    'equipe', (select coalesce(jsonb_agg(distinct q.p), '[]'::jsonb) from (
                                 select e.personne_id p from public.crescite_equipes e where e.date_id = x.id and e.present
                                 union
                                 select di.personne_id from public.crescite_distributions di
                                 where di.spectacle_id = x.spectacle_id and di.en_tournee
                                   and not exists (select 1 from public.crescite_equipes e
                                                   where e.date_id = x.id and e.personne_id = di.personne_id and not e.present)) q))
                    order by x.debut, x.id), '[]'::jsonb)
                  from public.crescite_dates x
                  join public.crescite_spectacles s on s.id = x.spectacle_id
                  left join public.crescite_lieux l on l.id = x.lieu_id
                  where x.debut <= a and coalesce(x.fin, x.debut) >= de and x.statut <> 'annulee'
                    and (admin or x.statut <> 'option' or public.crescite_membre_date(x.id))),
    'propositions', (select coalesce(jsonb_agg(jsonb_build_object('id', p.id, 'titre', p.titre, 'message', p.message,
                    'statut', p.statut, 'spectacle_id', p.spectacle_id, 'cree_le', p.cree_le,
                    'jours', (select jsonb_agg(jsonb_build_object('id', pj.id, 'debut', pj.debut, 'fin', pj.fin, 'journee', pj.journee,
                                'reponses', (select coalesce(jsonb_agg(jsonb_build_object('personne_id', r.personne_id,
                                               'reponse', r.reponse, 'commentaire', r.commentaire)), '[]'::jsonb)
                                             from public.crescite_propositions_reponses r
                                             where r.jour_id = pj.id and (admin or r.personne_id = moi)))
                              order by pj.debut)
                              from public.crescite_propositions_jours pj where pj.proposition_id = p.id),
                    'destinataires', (select jsonb_agg(jsonb_build_object('personne_id', d.personne_id,
                                        'courriel_statut', case when admin then d.courriel_statut end))
                                      from public.crescite_propositions_destinataires d
                                      where d.proposition_id = p.id and (admin or d.personne_id = moi)))
                    order by p.cree_le desc), '[]'::jsonb)
                  from public.crescite_propositions p
                  where (admin or exists (select 1 from public.crescite_propositions_destinataires d
                                          where d.proposition_id = p.id and d.personne_id = moi))
                    and exists (select 1 from public.crescite_propositions_jours pj
                                where pj.proposition_id = p.id and pj.debut < t1 and pj.fin > t0))
  );
end;
$$;

