-- vrai si la personne connectée est destinataire de cette proposition
create or replace function public.crescite_destinataire(p bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.crescite_propositions_destinataires d
                 where d.proposition_id = p and d.personne_id = public.crescite_moi())
$$;

-- les notifications connaissent les propositions
alter table public.crescite_notifications drop constraint if exists crescite_notifications_type_check;
