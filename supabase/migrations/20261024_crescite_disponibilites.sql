-- un agenda relié : à sa personne (l'administration le voit, sans l'adresse, et peut le retirer)
create policy dispo_lecture on public.crescite_agendas_lies for select to authenticated
  using (personne_id = (select public.crescite_moi()) or (select public.crescite_est_admin()));
create policy dispo_ajout on public.crescite_agendas_lies for insert to authenticated
  with check (personne_id = (select public.crescite_moi()));
create policy dispo_modification on public.crescite_agendas_lies for update to authenticated
  using (personne_id = (select public.crescite_moi())) with check (personne_id = (select public.crescite_moi()));
create policy dispo_suppression on public.crescite_agendas_lies for delete to authenticated
  using (personne_id = (select public.crescite_moi()) or (select public.crescite_est_admin()));

-- ses indisponibilités : la personne écrit les siennes (à la main) ; l'administration, toutes ; le reste de l'équipe
-- les voit par crescite_planning, sans le motif
create policy dispo_lecture on public.crescite_indisponibilites for select to authenticated
  using (personne_id = (select public.crescite_moi()) or (select public.crescite_est_admin()));
create policy dispo_ajout on public.crescite_indisponibilites for insert to authenticated
  with check ((select public.crescite_est_admin())
              or (personne_id = (select public.crescite_moi()) and source = 'manuel' and agenda_id is null));
