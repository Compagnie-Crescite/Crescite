-- proposer des dates (administration) : p = {titre, message, spectacle_id, date_id, jours: [{debut, fin, journee}],
-- personnes: [id…]} ; chaque personne est prévenue dans l'application et par courriel
create or replace function public.crescite_proposer(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  pid bigint;
  j jsonb;
  personne bigint;
begin
  if not public.crescite_est_admin() then
    raise exception 'Réservé aux administrateurs de la compagnie' using errcode = '42501';
  end if;
  if coalesce(jsonb_array_length(p -> 'jours'), 0) = 0 or coalesce(jsonb_array_length(p -> 'personnes'), 0) = 0 then
    raise exception 'Il faut au moins un jour et une personne' using errcode = '22023';
  end if;
  insert into public.crescite_propositions (titre, message, spectacle_id, date_id)
  values (coalesce(nullif(btrim(p ->> 'titre'), ''), 'Des dates à confirmer'), nullif(btrim(p ->> 'message'), ''),
          nullif(p ->> 'spectacle_id', '')::bigint, nullif(p ->> 'date_id', '')::bigint)
  returning id into pid;
  for j in select * from jsonb_array_elements(p -> 'jours') loop
    insert into public.crescite_propositions_jours (proposition_id, debut, fin, journee)
    values (pid, (j ->> 'debut')::timestamptz,
            coalesce(nullif(j ->> 'fin', '')::timestamptz, (j ->> 'debut')::timestamptz + interval '1 day'),
            coalesce((j ->> 'journee')::boolean, true));
  end loop;
  for personne in select distinct (x #>> '{}')::bigint from jsonb_array_elements(p -> 'personnes') x loop
    insert into public.crescite_propositions_reponses (jour_id, personne_id)
    select id, personne from public.crescite_propositions_jours where proposition_id = pid;
    insert into public.crescite_propositions_destinataires (proposition_id, personne_id) values (pid, personne);
  end loop;
  return pid;
end;
$$;

-- répondre (la personne elle-même, dans l'application)
create or replace function public.crescite_repondre(jour bigint, reponse_ text, commentaire_ text default null) returns void
language plpgsql security definer set search_path = public as $$
declare moi bigint := public.crescite_moi();
begin
  if moi is null then raise exception 'Réservé à l''équipe' using errcode = '42501'; end if;
  update public.crescite_propositions_reponses set reponse = nullif(reponse_, ''), commentaire = nullif(btrim(commentaire_), ''),
    repondu_le = now()
  where jour_id = jour and personne_id = moi;
  if not found then raise exception 'Cette proposition ne vous est pas adressée' using errcode = '42501'; end if;
end;
$$;

-- répondre d'un clic dans le courriel (fonction crescite-courriel, avec la clé de la personne)
create or replace function public.crescite_repondre_jeton(j text, jour bigint, reponse_ text) returns boolean
language plpgsql security definer set search_path = public as $$
declare d public.crescite_propositions_destinataires;
begin
  select * into d from public.crescite_propositions_destinataires where jeton = j and length(coalesce(j, '')) >= 32;
  if d.id is null or reponse_ not in ('oui', 'non', 'peut_etre') then return false; end if;
  update public.crescite_propositions_reponses r set reponse = reponse_, repondu_le = now()
  from public.crescite_propositions_jours pj
  where r.jour_id = jour and r.personne_id = d.personne_id and pj.id = r.jour_id and pj.proposition_id = d.proposition_id;
  return found;
end;
$$;

-- ce qu'un courriel ou la page de réponse affiche : la proposition, ses jours et les réponses de la personne
create or replace function public.crescite_proposition_jeton(j text) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'proposition', jsonb_build_object('id', p.id, 'titre', p.titre, 'message', p.message, 'statut', p.statut,
                                      'spectacle', (select s.titre from public.crescite_spectacles s where s.id = p.spectacle_id)),
    'personne', jsonb_build_object('prenom', pe.prenom, 'nom', pe.nom, 'email', v.email),
    'jours', (select jsonb_agg(jsonb_build_object('id', pj.id, 'debut', pj.debut, 'fin', pj.fin, 'journee', pj.journee,
                                                  'reponse', r.reponse) order by pj.debut)
              from public.crescite_propositions_jours pj
              left join public.crescite_propositions_reponses r on r.jour_id = pj.id and r.personne_id = d.personne_id
              where pj.proposition_id = p.id))
  from public.crescite_propositions_destinataires d
  join public.crescite_propositions p on p.id = d.proposition_id
  join public.crescite_personnes pe on pe.id = d.personne_id
  left join public.crescite_personnes_privees v on v.personne_id = d.personne_id
  where d.jeton = j and length(coalesce(j, '')) >= 32
$$;

-- chaque destinataire est prévenu : dans l'application (et sur son téléphone) et par courriel
create or replace function public.crescite_propositions_prevenir() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  p public.crescite_propositions;
  jeton text;
begin
  select * into p from public.crescite_propositions where id = new.proposition_id;
  perform public.crescite_notifier(array[new.personne_id], 'proposition', 'Des dates vous sont proposées', p.titre,
                                   null, p.spectacle_id, '#/proposition/' || p.id);
  select valeur into jeton from public.crescite_secrets where cle = 'jeton_push';
  if jeton is not null then
    begin
      perform net.http_post(
        url := 'https://omekkqjinvppadsoinvj.supabase.co/functions/v1/crescite-courriel',
        body := jsonb_build_object('destinataire_id', new.id),
        headers := jsonb_build_object('Content-Type', 'application/json', 'x-crescite-jeton', jeton));
    exception when others then
      raise notice 'courriel : %', sqlerrm;
    end;
  end if;
  return null;
end;
$$;
drop trigger if exists crescite_propositions_prevenir on public.crescite_propositions_destinataires;
create trigger crescite_propositions_prevenir after insert on public.crescite_propositions_destinataires
  for each row execute function public.crescite_propositions_prevenir();

-- une réponse arrive : l'administration est prévenue (les administrateurs qui ont une fiche)
create or replace function public.crescite_propositions_reponse_recue() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  qui text;
  pid bigint;
  titre_ text;
begin
  if new.reponse is null or new.reponse is not distinct from old.reponse then return null; end if;
  select coalesce(nullif(concat_ws(' ', pe.prenom, pe.nom), ''), 'Quelqu''un') into qui
  from public.crescite_personnes pe where pe.id = new.personne_id;
  select pj.proposition_id, p.titre into pid, titre_
  from public.crescite_propositions_jours pj join public.crescite_propositions p on p.id = pj.proposition_id where pj.id = new.jour_id;
  perform public.crescite_notifier(array(
      select v.personne_id from public.crescite_admins a join public.crescite_personnes_privees v on v.user_id = a.user_id
      where v.personne_id is distinct from new.personne_id),
    'proposition', 'Réponse : ' || qui, titre_, null, null, '#/proposition/' || pid);
  return null;
end;
$$;
drop trigger if exists crescite_propositions_reponse_recue on public.crescite_propositions_reponses;
create trigger crescite_propositions_reponse_recue after update on public.crescite_propositions_reponses
  for each row execute function public.crescite_propositions_reponse_recue();

