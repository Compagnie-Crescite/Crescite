-- Crescite : les disponibilités de l'équipe. Chacun dit quand il n'est pas libre, à la main ou en reliant son agenda
-- (Google Agenda, Apple, Outlook… par son adresse iCal secrète) ; toute l'équipe voit le planning de tous ;
-- l'administration propose des dates, et chacun répond dans l'application ou d'un clic dans le courriel reçu.
-- À exécuter après les quatre premiers scripts, de la même façon (SQL Editor → New query → coller → Run). Il peut être
-- relancé sans dommage et ne touche qu'à ce qui commence par crescite_ (plus pg_cron, pour relire les agendas reliés).
--
-- Ce que le script ajoute :
--   crescite_indisponibilites        une période où la personne n'est pas libre : saisie à la main, ou lue dans son
--                                    agenda relié. Toute l'équipe en voit les heures ; le motif reste à la personne et à
--                                    l'administration ; d'un agenda relié, seules les heures sont gardées (aucun titre)
--   crescite_agendas_lies            l'adresse iCal secrète d'un agenda personnel : la personne l'écrit, mais personne ne
--                                    peut la relire par l'API (seule la fonction crescite-agenda s'en sert)
--   crescite_personnes_privees.agenda_jeton
--                                    la clé du flux personnel des dates Crescite, à ajouter dans son Google Agenda
--   crescite_propositions (+ _jours, _destinataires, _reponses)
--                                    des dates proposées par l'administration à des personnes ; chacune répond par jour
--                                    (oui, non, peut-être) ; un courriel part à chacune (fonction crescite-courriel)
--   le planning                      crescite_planning(de, a) : les personnes, leurs indisponibilités, les dates de la
--                                    compagnie et les propositions, pour l'application de l'équipe et l'administration

begin;

-- ------------------------------------------------------------------------------------------------ les agendas reliés

create table if not exists public.crescite_agendas_lies (
  id bigint generated by default as identity primary key,
  personne_id bigint not null references public.crescite_personnes (id) on delete cascade,
  nom text not null default 'Mon agenda',
  url text not null,                               -- l'adresse iCal secrète : jamais relue par l'API
  actif boolean not null default true,
  derniere_synchro timestamptz,
  erreur text,
  nb_evenements integer,
  cree_le timestamptz not null default now()
);
create index if not exists crescite_agendas_lies_personne on public.crescite_agendas_lies (personne_id);

-- webcal:// devient https:// ; seules les adresses https sont acceptées
create or replace function public.crescite_agendas_lies_avant() returns trigger
language plpgsql as $$
begin
  new.url := regexp_replace(btrim(new.url), '^webcals?://', 'https://', 'i');
  if new.url !~* '^https://[^/\s]+\.[^/\s]+/' then
    raise exception 'Adresse d''agenda invalide : il faut l''adresse iCal (https://… ou webcal://…)' using errcode = '22023';
  end if;
  if tg_op = 'UPDATE' and new.url is distinct from old.url then new.erreur := null; new.derniere_synchro := null; end if;
  return new;
end;
$$;
drop trigger if exists crescite_agendas_lies_avant on public.crescite_agendas_lies;
create trigger crescite_agendas_lies_avant before insert or update on public.crescite_agendas_lies
  for each row execute function public.crescite_agendas_lies_avant();

-- ------------------------------------------------------------------------------------------------ les indisponibilités

create table if not exists public.crescite_indisponibilites (
