  using ((select public.crescite_est_admin()) or (personne_id = (select public.crescite_moi()) and source = 'manuel'))
  with check ((select public.crescite_est_admin())
              or (personne_id = (select public.crescite_moi()) and source = 'manuel' and agenda_id is null));
