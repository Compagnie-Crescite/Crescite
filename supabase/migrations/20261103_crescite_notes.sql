-- Crescite : les notes internes de l'administration (le quinzième script). À exécuter après les précédents, de la même
-- façon (SQL Editor → New query → coller → Run). Il peut être relancé sans dommage et ne touche qu'à ce qui commence par
-- crescite_.
--
-- Ce que le script ajoute :
--   crescite_notes        un fil de notes sur chaque fiche (une date, un lieu, une personne, une piste de diffusion) :
--                         le texte, les personnes mentionnées (@Prénom Nom), une pièce jointe (dans le stockage privé
--                         « crescite-equipe », sous notes/), épinglée ou non, l'auteur. Réservées aux administrateurs ;
--                         journalisées comme le reste.
--   les mentions          une personne mentionnée dans une note reçoit une notification dans son espace (type
--                         « message », avec le lien de la date quand la note porte sur une date). La base l'écrit seule.

begin;

create table if not exists public.crescite_notes (
  id bigint generated by default as identity primary key,
  cible_table text not null check (cible_table in ('crescite_dates', 'crescite_lieux', 'crescite_personnes', 'crescite_diffusion_prospects', 'crescite_spectacles')),
  cible_id bigint not null,
  texte text not null check (length(texte) between 1 and 4000),
  mentions bigint[] not null default '{}',          -- crescite_personnes.id
  epingle boolean not null default false,
  fichier text,                                     -- notes/<table>/<id>/<nom>, dans « crescite-equipe »
  fichier_nom text,
  auteur uuid default auth.uid(),
  auteur_nom text,
  cree_le timestamptz not null default now(),
  modifie_le timestamptz not null default now(),
  modifie_par uuid
);
create index if not exists crescite_notes_cible on public.crescite_notes (cible_table, cible_id, epingle desc, cree_le desc);

alter table public.crescite_notes enable row level security;
drop policy if exists notes_lecture on public.crescite_notes;
drop policy if exists notes_ajout on public.crescite_notes;
drop policy if exists notes_modification on public.crescite_notes;
drop policy if exists notes_suppression on public.crescite_notes;
create policy notes_lecture on public.crescite_notes for select to authenticated using ((select public.crescite_est_admin()));
create policy notes_ajout on public.crescite_notes for insert to authenticated with check ((select public.crescite_est_admin()));
create policy notes_modification on public.crescite_notes for update to authenticated using ((select public.crescite_est_admin()));
create policy notes_suppression on public.crescite_notes for delete to authenticated using ((select public.crescite_est_admin()));
grant select, insert, update, delete on public.crescite_notes to authenticated;
grant usage, select on sequence public.crescite_notes_id_seq to authenticated;

-- modifie_le et modifie_par comme sur les autres tables (crescite_toucher existe depuis le script de base ; sinon, rien)
do $$ begin
  if exists (select 1 from pg_proc where proname = 'crescite_toucher' and pronamespace = 'public'::regnamespace) then
    execute 'drop trigger if exists crescite_notes_toucher on public.crescite_notes';
    execute 'create trigger crescite_notes_toucher before update on public.crescite_notes for each row execute function public.crescite_toucher()';
  end if;
end $$;

-- le journal (le script de base) : ajouts, modifications et suppressions de notes y vont, avec « Revenir » et la corbeille
drop trigger if exists crescite_notes_journal on public.crescite_notes;
create trigger crescite_notes_journal after insert or update or delete on public.crescite_notes
  for each row execute function public.crescite_journaliser();

-- une personne mentionnée reçoit une notification (une par mention nouvelle) ; jamais l'auteur pour lui-même
create or replace function public.crescite_notes_mentions() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  p bigint;
  moi bigint := (select v.personne_id from public.crescite_personnes_privees v where v.user_id = new.auteur limit 1);
  d bigint := case when new.cible_table = 'crescite_dates' then new.cible_id else null end;
  s bigint := case when new.cible_table = 'crescite_spectacles' then new.cible_id
                   when new.cible_table = 'crescite_dates' then (select x.spectacle_id from public.crescite_dates x where x.id = new.cible_id) else null end;
  sujet text;
begin
  sujet := case new.cible_table
    when 'crescite_dates' then (select coalesce(sp.titre, 'une date') || ' · ' || to_char(x.debut, 'DD/MM/YYYY') from public.crescite_dates x left join public.crescite_spectacles sp on sp.id = x.spectacle_id where x.id = new.cible_id)
    when 'crescite_lieux' then (select coalesce(x.nom, x.commune) from public.crescite_lieux x where x.id = new.cible_id)
    when 'crescite_personnes' then 'votre fiche'
    when 'crescite_diffusion_prospects' then (select x.structure from public.crescite_diffusion_prospects x where x.id = new.cible_id)
    when 'crescite_spectacles' then (select x.titre from public.crescite_spectacles x where x.id = new.cible_id)
    else null end;
  foreach p in array coalesce(new.mentions, '{}') loop
    if p is null or p = moi then continue; end if;
    if tg_op = 'UPDATE' and p = any (coalesce(old.mentions, '{}')) then continue; end if;
    if not exists (select 1 from public.crescite_personnes x where x.id = p) then continue; end if;
    insert into public.crescite_notifications (personne_id, type, titre, texte, date_id, spectacle_id, lien)
    values (p, 'message', coalesce(new.auteur_nom, 'L’administration') || ' vous mentionne' || coalesce(' (' || sujet || ')', ''), left(new.texte, 300), d, s,
            case when d is not null then '#/date/' || d else null end);
  end loop;
  return null;
end;
$$;
drop trigger if exists crescite_notes_mentions on public.crescite_notes;
create trigger crescite_notes_mentions after insert or update of mentions on public.crescite_notes
  for each row execute function public.crescite_notes_mentions();

commit;

notify pgrst, 'reload schema';

select 'notes', case when exists (select 1 from pg_tables where schemaname = 'public' and tablename = 'crescite_notes') then 'installées' else 'manquantes' end;
