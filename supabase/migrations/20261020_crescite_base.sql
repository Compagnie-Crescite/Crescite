-- la saison se déduit du début quand on ne la donne pas, et suit le début quand il change
create or replace function public.crescite_dates_avant() returns trigger
language plpgsql as $$
begin
  if new.saison is null or new.saison = '' then
    new.saison := public.crescite_saison(new.debut);
  elsif tg_op = 'UPDATE' then
    if new.debut is distinct from old.debut and new.saison = old.saison then
      new.saison := public.crescite_saison(new.debut);
    end if;
  end if;
  if new.fin is null then new.fin := new.debut; end if;
  return new;
end;
$$;

-- une répétition, une date « autre » n'est jamais sur le site public (une résidence peut y aller : douzième script)
create or replace function public.crescite_dates_nature() returns trigger
language plpgsql as $$
begin
  -- une répétition, une date « autre » : jamais sur le site ; une représentation, une résidence : sa case « visible »
  -- (une résidence va sur le site depuis le douzième script, 20261031_crescite_residences.sql)
  if new.nature not in ('representations', 'residence') then new.visible := false; end if;
  return new;
end;
$$;

-- le début et la fin d'une date suivent ses représentations
create or replace function public.crescite_dates_bornes(d bigint) returns void
language plpgsql security definer set search_path = public as $$
declare mini date; maxi date;
begin
  select min(jour), max(jour) into mini, maxi from public.crescite_representations where date_id = d;
  if mini is not null then
    update public.crescite_dates set debut = mini, fin = maxi, precision = 'jour'
     where id = d and (debut, fin, precision) is distinct from (mini, maxi, 'jour');
  end if;
end;
$$;

create or replace function public.crescite_representations_apres() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    perform public.crescite_dates_bornes(old.date_id);
    return null;
  end if;
  perform public.crescite_dates_bornes(new.date_id);
  if tg_op = 'UPDATE' then
    if old.date_id <> new.date_id then perform public.crescite_dates_bornes(old.date_id); end if;
  end if;
  return null;
end;
$$;

