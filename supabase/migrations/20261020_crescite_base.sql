-- Crescite : la base de la compagnie, dans le projet Supabase du site adrienvada.fr (décision d'Adrien, octobre 2026).
--
-- Tout ce qui appartient à la compagnie porte le préfixe crescite_ (tables, fonctions, dossier de photos « crescite »).
-- Le script ne touche à rien d'autre : ni aux tables du site personnel (representations, carnet, carnet_acces), ni à
-- leurs règles. Le jour où la compagnie aura son propre projet, tout ce qui commence par crescite_ s'y déplace tel quel.
--
-- À exécuter une fois, d'un seul bloc, dans Supabase : SQL Editor → New query → coller ce fichier → Run.
-- Il peut être relancé sans dommage : il ne crée que ce qui manque et remet les fonctions et les règles à jour.
--
-- Ce que la base contient :
--   crescite_spectacles        le contenu de chaque spectacle (textes, distribution, univers, action culturelle…)
--   crescite_lieux             les salles, festivals et établissements, avec leurs coordonnées
--   crescite_dates             les dates de tournée : une ligne de l'agenda (un spectacle, un lieu, une période)
--   crescite_representations   les représentations de chaque date : jour, heure, public ; plusieurs par jour
--   crescite_ateliers          les ateliers proposés (le catalogue)
--   crescite_seances           les séances d'atelier menées dans les établissements
--   crescite_textes            les autres textes du site (présentation de la compagnie, actions culturelles…)
--   crescite_dates_suivi, crescite_lieux_suivi   le suivi interne (organisateur, contacts, notes) : jamais publié
--   crescite_journal           chaque modification, avec son auteur, pour pouvoir revenir en arrière
--   crescite_admins            les comptes qui peuvent modifier (les autres ne font que lire ce qui est publié)

begin;

-- ------------------------------------------------------------------------------------------------ fonctions communes

create table if not exists public.crescite_admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  nom text,
  cree_le timestamptz not null default now()
);

-- vrai si la personne connectée administre le site de la compagnie
create or replace function public.crescite_est_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.crescite_admins where user_id = auth.uid())
$$;

-- la saison d'une date : de septembre à août (« 2026-2027 »)
create or replace function public.crescite_saison(j date) returns text
language sql immutable as $$
  select case when extract(month from j) >= 9
    then extract(year from j)::int::text || '-' || (extract(year from j)::int + 1)::text
    else (extract(year from j)::int - 1)::text || '-' || extract(year from j)::int::text end
$$;

-- date et auteur de la dernière modification
create or replace function public.crescite_touche() returns trigger
language plpgsql as $$
begin
  new.modifie_le := now();
  if auth.uid() is not null then new.modifie_par := auth.uid(); end if;
  return new;
end;
$$;

