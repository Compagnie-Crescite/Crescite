create or replace function public.crescite_journaliser() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  avant jsonb;
  apres jsonb;
  rangee jsonb;
begin
  if tg_op <> 'INSERT' then avant := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then apres := to_jsonb(new); end if;
  rangee := coalesce(apres, avant);
  insert into public.crescite_journal (table_nom, ligne, operation, avant, apres)
  values (tg_table_name, coalesce(rangee ->> 'id', rangee ->> 'date_id', rangee ->> 'lieu_id', rangee ->> 'cle'), tg_op, avant, apres);
  return null;
end;
$$;

-- la version des données publiées : change à chaque enregistrement (secours du temps réel)
create or replace function public.crescite_version() returns bigint
language sql stable security definer set search_path = public as $$
  select coalesce(max(id), 0) from public.crescite_journal
$$;

