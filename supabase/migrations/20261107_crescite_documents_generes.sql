-- Crescite : les documents générés à l'abri (le vingtième script). À exécuter après les précédents, de la même façon
-- (SQL Editor → New query → coller → Run). Il peut être relancé sans dommage et ne touche qu'à ce qui commence par
-- crescite_.
--
-- Pourquoi : les devis, contrats, factures et fiches techniques générés par l'administration étaient gardés dans
-- crescite_textes (clé « documents:generes »), une table que le site public lit en entier ; leur numéro était compté
-- dans le navigateur, et la liste réécrite d'un bloc (deux générations simultanées : le même numéro, l'une effaçait
-- l'autre).
--
-- Ce que le script ajoute :
--   crescite_documents_generes   un document par ligne, réservé aux administrateurs : son type, son numéro (DEV-2026-003,
--                                unique), la ou les dates, la piste ou la demande de devis d'où il vient, le destinataire,
--                                les montants, ses valeurs, et la page telle qu'émise (une réimpression la reproduit à
--                                l'identique). Ce qui suit l'émission : l'échéance, le paiement, l'annulation, une note.
--                                Un document émis ne change plus ; une facture ne se supprime pas (on l'annule).
--   crescite_emettre_document()  le seul moyen d'en créer un : la base donne le numéro, le suivant de l'année pour ce type,
--                                sous un verrou (deux émissions simultanées ont deux numéros).
--   crescite_textes              la clé « documents:generes » y est reprise puis effacée ; ses clés « modele:… » et
--                                « modele-date:… » ne sont plus lues que par l'administration.

begin;

create table if not exists public.crescite_documents_generes (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('devis', 'contrat', 'facture', 'fiche_technique')),
  annee integer not null,
  rang integer not null check (rang > 0),
  numero text not null unique,
  date_id bigint references public.crescite_dates (id) on delete set null,
  dates bigint[] not null default '{}',             -- toutes les dates d'un document qui en couvre plusieurs (une tournée)
  prospect_id bigint references public.crescite_diffusion_prospects (id) on delete set null,
  demande_id bigint references public.crescite_devis_demandes (id) on delete set null,
  structure text,
  montant_ht numeric(12, 2),
  montant_ttc numeric(12, 2),
  valeurs jsonb not null default '{}',
  html text,                                        -- la page telle qu'émise
  emis_le timestamptz not null default now(),
  echeance date,                                    -- une facture : à payer avant le
  paye_le date,
  annule_le timestamptz,
  note text,
  cree_par uuid default auth.uid(),
  modifie_le timestamptz not null default now(),
  modifie_par uuid,
  unique (type, annee, rang)
);
create index if not exists crescite_documents_generes_date on public.crescite_documents_generes (date_id);
create index if not exists crescite_documents_generes_piste on public.crescite_documents_generes (prospect_id);

alter table public.crescite_documents_generes enable row level security;
drop policy if exists docgen_lecture on public.crescite_documents_generes;
drop policy if exists docgen_modification on public.crescite_documents_generes;
drop policy if exists docgen_suppression on public.crescite_documents_generes;
create policy docgen_lecture on public.crescite_documents_generes for select to authenticated using ((select public.crescite_est_admin()));
create policy docgen_modification on public.crescite_documents_generes for update to authenticated using ((select public.crescite_est_admin()));
create policy docgen_suppression on public.crescite_documents_generes for delete to authenticated using ((select public.crescite_est_admin()));
-- (pas d'insertion directe : crescite_emettre_document donne le numéro)
revoke all on public.crescite_documents_generes from anon, authenticated;
grant select, update, delete on public.crescite_documents_generes to authenticated;
grant all on public.crescite_documents_generes to service_role;

-- un document émis ne change plus (son numéro, ses montants, sa page) ; ce qui le suit, si : échéance, paiement,
-- annulation, note, et les liens (une date supprimée le délie). Une facture ne se supprime pas : on l'annule.
create or replace function public.crescite_documents_generes_garde() returns trigger
language plpgsql set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    if old.type = 'facture' then
      raise exception 'Une facture émise ne se supprime pas : annulez-la (et émettez un avoir si besoin).' using errcode = '42501';
    end if;
    return old;
  end if;
  if new.type is distinct from old.type or new.annee is distinct from old.annee or new.rang is distinct from old.rang
     or new.numero is distinct from old.numero or new.html is distinct from old.html or new.valeurs is distinct from old.valeurs
     or new.montant_ht is distinct from old.montant_ht or new.montant_ttc is distinct from old.montant_ttc
     or new.structure is distinct from old.structure or new.emis_le is distinct from old.emis_le then
    raise exception 'Un document émis ne change plus : émettez-en un nouveau.' using errcode = '42501';
  end if;
  new.modifie_le := now();
  new.modifie_par := auth.uid();
  return new;
end;
$$;
drop trigger if exists crescite_documents_generes_garde on public.crescite_documents_generes;
create trigger crescite_documents_generes_garde before update or delete on public.crescite_documents_generes
  for each row execute function public.crescite_documents_generes_garde();

-- le journal (le script de base) : émission, paiement, annulation, suppression y vont
drop trigger if exists crescite_documents_generes_journal on public.crescite_documents_generes;
create trigger crescite_documents_generes_journal after insert or update or delete on public.crescite_documents_generes
  for each row execute function public.crescite_journaliser();

-- émettre un document : la base donne le numéro (le suivant de l'année pour ce type, sous un verrou) et le pose dans la
-- page à la place de {{numero}}
create or replace function public.crescite_emettre_document(type_ text, html_ text, valeurs_ jsonb default '{}',
    date_ bigint default null, dates_ bigint[] default '{}', prospect_ bigint default null, demande_ bigint default null,
    structure_ text default null, ht numeric default null, ttc numeric default null, echeance_ date default null)
returns public.crescite_documents_generes
language plpgsql security definer set search_path = public as $$
declare
  an integer := extract(year from public.crescite_aujourdhui_paris())::integer;
  pre text := case type_ when 'devis' then 'DEV' when 'contrat' then 'CES' when 'facture' then 'FAC' when 'fiche_technique' then 'FT' end;
  r integer;
  num text;
  sortie public.crescite_documents_generes;
begin
  if not public.crescite_est_admin() then
    raise exception 'Réservé aux administrateurs de la compagnie' using errcode = '42501';
  end if;
  if pre is null then raise exception 'Type de document inconnu : %', type_ using errcode = '22023'; end if;
  perform pg_advisory_xact_lock(hashtext('crescite_documents_generes:' || type_ || ':' || an));
  select coalesce(max(rang), 0) + 1 into r from public.crescite_documents_generes where type = type_ and annee = an;
  num := pre || '-' || an || '-' || lpad(r::text, 3, '0');
  insert into public.crescite_documents_generes (type, annee, rang, numero, date_id, dates, prospect_id, demande_id, structure,
                                                 montant_ht, montant_ttc, valeurs, html, echeance)
  values (type_, an, r, num, date_, coalesce(dates_, '{}'), prospect_, demande_, structure_, ht, ttc,
          coalesce(valeurs_, '{}') || jsonb_build_object('numero', num), replace(coalesce(html_, ''), '{{numero}}', num), echeance_)
  returning * into sortie;
  return sortie;
end;
$$;
revoke all on function public.crescite_emettre_document(text, text, jsonb, bigint, bigint[], bigint, bigint, text, numeric, numeric, date) from public, anon;
grant execute on function public.crescite_emettre_document(text, text, jsonb, bigint, bigint[], bigint, bigint, text, numeric, numeric, date) to authenticated;

-- les documents déjà gardés dans crescite_textes : repris (sans leur page, qui n'était pas gardée), puis effacés de la table
-- publique
insert into public.crescite_documents_generes (type, annee, rang, numero, date_id, prospect_id, structure, montant_ttc, valeurs, emis_le)
select d ->> 'type', split_part(d ->> 'numero', '-', 2)::integer, split_part(d ->> 'numero', '-', 3)::integer, d ->> 'numero',
       (select x.id from public.crescite_dates x where x.id::text = d ->> 'date_id'),
       (select x.id from public.crescite_diffusion_prospects x where x.id::text = d ->> 'prospect_id'),
       d ->> 'structure', nullif(d ->> 'montant_ttc', '')::numeric, coalesce(d -> 'valeurs', '{}'),
       coalesce(nullif(d ->> 'le', '')::timestamptz, now())
  from public.crescite_textes t, jsonb_array_elements(case when jsonb_typeof(t.valeur) = 'array' then t.valeur else '[]' end) d
 where t.cle = 'documents:generes'
   and d ->> 'type' in ('devis', 'contrat', 'facture', 'fiche_technique')
   and d ->> 'numero' ~ '^[A-Z]+-[0-9]{4}-[0-9]+$'
on conflict do nothing;
delete from public.crescite_textes where cle = 'documents:generes';

-- crescite_textes : ses clés internes ne sont plus publiques (même règle dans le script de base)
drop policy if exists lecture on public.crescite_textes;
create policy lecture on public.crescite_textes for select to anon, authenticated
  using (not (cle like 'documents:%' or cle like 'modele:%' or cle like 'modele-date:%') or (select public.crescite_est_admin()));

-- le temps réel : un document émis par une administratrice apparaît chez l'autre
do $$ begin
  begin
    alter publication supabase_realtime add table public.crescite_documents_generes;
  exception
    when duplicate_object then null;
    when others then raise notice 'temps réel, crescite_documents_generes : %', sqlerrm;
  end;
end $$;

commit;

notify pgrst, 'reload schema';

select 'documents générés', case when exists (select 1 from pg_tables where schemaname = 'public' and tablename = 'crescite_documents_generes')
  then 'à l''abri' else 'manquants' end
union all
select 'textes publics', case when exists (select 1 from public.crescite_textes where cle = 'documents:generes')
  then 'la clé documents:generes est encore là : relancez ce script' else 'sans document généré' end;
